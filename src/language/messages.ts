const normalize = (s: string) =>
  s
    .toLowerCase()
    .replace(/[–—]/g, '-')
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/\s+/g, ' ')
    .replace(/[\s.]+$/, '')
    .trim();

const PLACEHOLDER = /<[^>]+>|\((?:filename|name|tagname\.param|value)\)|@\d/;

function pattern(text: string): RegExp {
  const parts = normalize(text).split(new RegExp(PLACEHOLDER, 'g'));
  return new RegExp(`^${parts.map((p) => p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('.+?')}$`);
}

let compiled: { pattern: RegExp; message: CompilerMessage }[] | undefined;

/** The catalogue entry for a message as a listing prints it, if there is one. */
export function lookupMessage(text: string): CompilerMessage | undefined {
  compiled ??= MESSAGES.map(([t, source, severity]) => ({ pattern: pattern(t), message: { text: t, source, severity } }));
  const n = normalize(text);
  // Literal entries first, so "Not found" does not lose to "<name> not found".
  return (
    compiled.find((c) => !PLACEHOLDER.test(c.message.text) && c.pattern.test(n))?.message ??
    compiled.find((c) => c.pattern.test(n))?.message
  );
}

/** What a source column means, for hovers: "pass 2 (type checking)". */
export function describeSource(source: string): string {
  const parts = source.split('/').map((s) => {
    if (s === 'P1') return 'pass 1 (syntax)';
    if (s === 'P2') return 'pass 2 (type checking)';
    if (/^P3|^(MC|PM|APM)$/.test(s)) return 'pass 3 (code generation)';
    if (s === 'LK') return 'the linker';
    if (s === 'CX') return 'data access';
    return s;
  });
  return [...new Set(parts)].join(' or ');
}

