const sets = new Map<string, Set<string>>();
const setOf = (key: string, text: string | undefined) => {
  let s = sets.get(key);
  if (!s) sets.set(key, (s = new Set((text ?? '').split(' ').filter(Boolean))));
  return s;
};

/** Whether `param` exists on points of database type `type`; undefined when the type is not known. */
export function typeHasParameter(type: string, param: string): boolean | undefined {
  if (!(type in BY_TYPE)) return undefined;
  return setOf(type, BY_TYPE[type]).has(param) || setOf('', ANY_TYPE).has(param);
}

export function isViewOnly(type: string, param: string): boolean {
  return setOf(`view:${type}`, VIEW_ONLY[type]).has(param);
}
